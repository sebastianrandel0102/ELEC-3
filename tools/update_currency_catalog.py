"""Refresh bundled fiat metadata from SIX (ISO 4217) and Unicode CLDR.

Run: py -3 tools/update_currency_catalog.py
No exchange rates are bundled. Review the diff before releasing catalog updates.
"""
import json
import pathlib
import re
import urllib.request
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
SIX = 'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml'
CLDR = 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-numbers-full/main/en/currencies.json'


def generate(xml, cldr, provider_catalog):
    root = ET.fromstring(xml)
    names = json.loads(cldr)['main']['en']['numbers']['currencies']
    # Funds, metals, accounting units, testing codes and no-currency are not fiat.
    excluded = {'BOV', 'CHE', 'CHW', 'CLF', 'COU', 'MXV', 'USN', 'UYI', 'UYW',
                'XAD', 'XAG', 'XAU', 'XBA', 'XBB', 'XBC', 'XBD', 'XDR', 'XPD',
                'XPT', 'XSU', 'XTS', 'XUA', 'XXX'}
    currencies = {}
    for entry in root.findall('.//CcyNtry'):
        code = entry.findtext('Ccy')
        digits = entry.findtext('CcyMnrUnts')
        if not code or code in excluded or not (digits or '').isdigit():
            continue
        row = currencies.setdefault(code, {
            'name': names.get(code, {}).get('displayName', entry.findtext('CcyNm')),
            'symbol': names.get(code, {}).get('symbol', code),
            'digits': int(digits), 'regions': []})
        region = entry.findtext('CtryNm').title().replace(' (The)', '')
        if region not in row['regions']:
            row['regions'].append(region)
    quote = lambda s: json.dumps(s, ensure_ascii=False).replace('$', '\\$')
    lines = ['// GENERATED by tools/update_currency_catalog.py. Do not hand-edit.',
             '// SIX ISO 4217 List One; English names/symbols: Unicode CLDR.',
             "const currencyCatalogPublished = " + quote(root.attrib['Pblshd']) + ';',
             'const currencyCatalogRows = <(String, String, String, int, List<String>)>[']
    for code, row in sorted(currencies.items()):
        regions = ', '.join(map(quote, row['regions']))
        lines.append(f'  ({quote(code)}, {quote(row["name"])}, {quote(row["symbol"])}, {row["digits"]}, [{regions}]),')
    lines.append('];')
    provider_codes = set(re.findall(r'<td[^>]*>\s*([A-Z]{3})\s*</td>', provider_catalog)) - {'KPW'}
    if len(provider_codes) < 150:
        raise ValueError('The provider catalog changed; review before generating.')
    lines.append('// Documented provider coverage; quotes are validated at runtime.')
    lines.append('const providerCatalogCodes = <String>{' + ', '.join(map(quote, sorted(provider_codes))) + '};\n')
    (ROOT / 'lib/currency_catalog_data.dart').write_text('\n'.join(lines), encoding='utf-8')
    # Keep the client catalog and rules denomination checks synchronized.
    rules_path = ROOT / 'firestore.rules'
    rules = rules_path.read_text(encoding='utf-8')
    expression = 'function validCurrency(code) { return code is string && code.matches(\'^(%s)$\'); }' % '|'.join(sorted(currencies))
    rules, count = re.subn(r'function validCurrency\(code\)\s*\{[^}]+\}', lambda _: expression, rules)
    if count != 1:
        raise ValueError('Review the currency validation rule before updating the catalog.')
    zero = ','.join("'" + code + "'" for code, row in sorted(currencies.items()) if row['digits'] == 0)
    three = ','.join("'" + code + "'" for code, row in sorted(currencies.items()) if row['digits'] == 3)
    tolerance = "function moneyTolerance(code) { return code == 'PHP' ? 0.00500001 : code in [%s] ? 0.50000001 : code in [%s] ? 0.00050001 : 0.00500001; }" % (zero, three)
    rules, count = re.subn(r'function moneyTolerance\(code\)\s*\{[^}]+\}', lambda _: tolerance, rules)
    if count != 1:
        raise ValueError('Review the monetary precision rule before updating the catalog.')
    rules_path.write_text(rules, encoding='utf-8')
    print(f'{len(currencies)} active fiat currencies; SIX publication {root.attrib["Pblshd"]}')


if __name__ == '__main__':
    generate(urllib.request.urlopen(SIX, timeout=30).read(),
             urllib.request.urlopen(CLDR, timeout=30).read(),
             urllib.request.urlopen('https://www.exchangerate-api.com/docs/supported-currencies', timeout=30).read().decode())
